/** Longest tokens first so "shorad" / "destroyer" win over short fragments. */
export const TYPE_TOKEN_LIST: { token: string; type: UnitType }[] = Object.values(CATALOG)
  .flatMap((c) => c.tokens.map((token) => ({ token, type: c.type })))
  .sort((a, b) => b.token.length - a.token.length);

export const UNIT_TYPES = Object.keys(CATALOG) as UnitType[];

export function createUnit(
  type: UnitType,
  opts: { side: Unit["side"]; lat: number; lng: number; name?: string; notes?: string },
): Unit {
  const spec = CATALOG[type];
  return {
    id: uid("u"),
    name: opts.name ?? `${opts.side.toUpperCase()} ${spec.label}`,
    type,
    domain: spec.domain,
    side: opts.side,
    lat: opts.lat,
    lng: opts.lng,
    startLat: opts.lat,
    startLng: opts.lng,
    status: "ready",
    notes: opts.notes ?? "",
    speed: spec.speed,
    waypoints: [],
    waypointIndex: 0,
    maxHealth: spec.maxHealth,
    health: spec.maxHealth,
    damage: spec.damage,
    canTarget: [...spec.canTarget],
    detectionRangeKm: spec.detectionRangeKm,
    engagementRangeKm: spec.engagementRangeKm,
    fireCooldownSec: spec.fireCooldownSec,
    cooldownLeft: 0,
    magazine: spec.magazine,
    ammo: spec.magazine,
    reloadSec: spec.reloadSec,
    reloadLeft: 0,
    targetId: null,
  };
}

export function cloneUnits(units: Unit[]): Unit[] {
  return units.map((u) => ({
    ...u,
    canTarget: [...u.canTarget],
    waypoints: u.waypoints.map((w) => ({ ...w })),
  }));
}
